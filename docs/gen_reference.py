"""Generate the language-neutral part of the reference page from urdf2vla's skill registry.

  python docs/gen_reference.py      # writes docs/snippets/skills-table.md (included by reference.md and reference.ja.md)

Run it whenever a skill, its inputs/outputs or its options change. CI builds fail if the file is out of date
(`python docs/gen_reference.py --check`).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "snippets" / "skills-table.md"
sys.path.insert(0, str(ROOT / "src"))


def _code(items: list[str]) -> str:
    # "a | b" in the registry means "a or b"; a pipe would split the Markdown table cell
    return "<br>".join(" or ".join(f"`{alt}`" for alt in i.split(" | ")) for i in items) or "—"


def render() -> str:
    from urdf2vla.cli import build_parser  # noqa: F401  registers every skill
    from urdf2vla.registry import OPTIONAL, PIPELINE, SKILLS

    lines = [
        "<!-- generated by docs/gen_reference.py from src/urdf2vla/registry.py; do not edit -->",
        "",
        "| Skill | Runs in | Needs | Reads | Writes | Options |",
        "|---|---|---|---|---|---|",
    ]
    for name in [*PIPELINE, *OPTIONAL]:
        s = SKILLS[name].describe()
        opts = "<br>".join(f"`{' '.join(o['flags'])}`" for o in s["options"]) or "—"
        lines.append(
            f"| `{name}` | {s['runs_in']} | {_code(s['requires'])} | {_code(s['inputs'])} | {_code(s['outputs'])} | {opts} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python docs/gen_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
